-- ===========================================================================
-- Mesa 2.0 — base de conocimiento (nueva, no existe en `ticketing`)
--
-- Los artículos son el primer paso del portal: antes de abrir un ticket, el
-- empleado busca aquí. El buscador del portal consulta título, resumen y
-- contenido; cada artículo acumula visitas y votos «útil / no útil».
--
-- Las categorías (1..5) son las mismas de la semilla del esquema: Hardware,
-- Software, Redes, Accesos y Correo y Comunicaciones.
-- ===========================================================================

CREATE TABLE articulos_kb (
    id_articulo    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           VARCHAR(120) NOT NULL UNIQUE,
    titulo         VARCHAR(150) NOT NULL,
    resumen        VARCHAR(300) NOT NULL,
    contenido      TEXT NOT NULL,
    id_categoria   INT NOT NULL,
    publicado      BOOLEAN NOT NULL DEFAULT TRUE,
    visitas        INT NOT NULL DEFAULT 0,
    votos_util     INT NOT NULL DEFAULT 0,
    votos_no_util  INT NOT NULL DEFAULT 0,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_articulos_categoria FOREIGN KEY (id_categoria)
        REFERENCES categorias (id_categoria) ON DELETE RESTRICT
);

CREATE INDEX idx_articulos_kb_categoria ON articulos_kb (id_categoria);

